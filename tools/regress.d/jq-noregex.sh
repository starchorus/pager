# shellcheck shell=sh
# tools/regress.d/jq-noregex.sh -- the device's jq is built WITHOUT the Oniguruma regex library.
# Measured on the device (OpenWrt 24.10.1, BusyBox 1.36.1, mips):  jq -n '"abc"|test("b")'  answers
# "jq was compiled without ONIGURUMA regex library. match/test/sub and related functions are not
# available." and exits 5, while ascii_up/downcase, l/rtrimstr, startswith, contains and split/1 work.
# Band counts or an open/WEP figure computed with test()/sub() filters would come out EMPTY on the device
# -- silently, because q() sends jq's stderr to /dev/null. starchorus-display.sh is therefore regex-free
# (JQLIB: bandnorm/secupper/isopenwep/sectag); the five rows below keep it that way and pin what the
# replacements MEAN.
# Sourced by tools/regress.sh with cwd = repo root, after the core rows. Only JQR_* names are set.
#
# R1 static  : neither starchorus-display.sh copy may CALL a jq regex builtin outside a comment line.
# R2 runtime : every screen x every fixture, run twice through ONE generated wrapper "jq" that is
#   switched between the real jq and the device's jq by $STARCHORUS_NRX, then compared byte for byte. The
#   wrapper shadows the regex builtins with definitions that raise the device's error, which is what
#   the no-oniguruma build does at CALL time -- a regex call in a branch that is never taken stays
#   harmless there and here, which a static grep could not model. Two vacuity guards sit in front of
#   R2: the wrapper must actually bite (exit 5 with STARCHORUS_NRX=1, exit 0 without), and the simulated
#   run must still print real band counts -- otherwise R2 could pass on two identically empty screens.
#   A frozen `date` sits next to the wrapper so the "Nh ago" line cannot flip between the two runs.
# R3 oracle : a fixed table of band/security inputs and their expected normalised values, asserted
#   against the JQLIB literal lifted out of the shipped script. R2 cannot see the normalisation
#   itself change (it compares the script with itself); R3 is the row that can. It pins the _WS membership
#   at BOTH ends (_wsprobe/_lwsprobe), all three _rtrimws points inside bandnorm, and the leading
#   whitespace the page's .trim() removes.
# R4 types  : screen_top rendered from a non-string ssid/security/band, both jq builds.

JQR_PAY=library/user/reconnaissance/starchorus/starchorus-display.sh
JQR_D="$R/out/$P-jqnrx"
JQR_BIN="$JQR_D/bin"
JQR_RE='(^|[^A-Za-z0-9_.])(test|match|sub|gsub|capture|scan|splits)[[:space:]]*\('
JQR_RE2='(^|[^A-Za-z0-9_.])split[[:space:]]*\([^)]*;'

# ---- R1: static, both copies (comment lines are dropped first: a regex call inside a comment is inert,
# and the file's own prose legitimately contains things like "scan (source ...)").
JQR_HIT=$(for JQR_F in starchorus-display.sh "$JQR_PAY"; do
            grep -vE '^[[:space:]]*#' "$JQR_F" | grep -nE "$JQR_RE|$JQR_RE2" | sed "s|^|    $JQR_F line |"
          done)
JQR_N=$(printf '%s' "$JQR_HIT" | grep -c .)
if [ "$JQR_N" = 0 ]; then
  row "display jq filters regex-free (both copies)" PASS
else
  row "display jq filters call a regex builtin ($JQR_N site(s))" FAIL
  printf '%s\n' "$JQR_HIT"
fi

# ---- R2: runtime, the whole dashboard through a jq that behaves like the device's
rm -rf "$JQR_D"; mkdir -p "$JQR_BIN"
JQR_JQ=$(command -v jq); JQR_DATE=$(command -v date); JQR_NOW=1789600000
cat > "$JQR_BIN/jq" <<'K13JQ'
#!/bin/sh
# generated by tools/regress.d/jq-noregex.sh -- STARCHORUS_NRX=1 turns this into the device's jq
set -u
REAL=${STARCHORUS_REAL_JQ:-}
[ -x "$REAL" ] || { echo "nrx-jq: STARCHORUS_REAL_JQ is not an executable jq" >&2; exit 2; }
[ "${STARCHORUS_NRX:-0}" = 1 ] || exec "$REAL" "$@"
PRELUDE='def _noregex: error("jq was compiled without ONIGURUMA regex library.\n             match/test/sub and related functions are not available.");
def test(a): _noregex; def test(a;b): _noregex;
def match(a): _noregex; def match(a;b): _noregex;
def capture(a): _noregex; def capture(a;b): _noregex;
def scan(a): _noregex; def scan(a;b): _noregex;
def split(a;b): _noregex;
def splits(a): _noregex; def splits(a;b): _noregex;
def sub(a;b): _noregex; def sub(a;b;c): _noregex;
def gsub(a;b): _noregex; def gsub(a;b;c): _noregex;
'
total=$#; i=0; seen=0
while [ "$i" -lt "$total" ]; do
  a=$1; shift; i=$((i + 1))
  case $a in
    -f|--from-file|--args|--jsonargs|--)
      echo "nrx-jq: $a is not modelled by this wrapper" >&2; exit 2 ;;
    --arg|--argjson|--slurpfile|--rawfile)
      set -- "$@" "$a" "$1" "$2"; shift 2; i=$((i + 2)); continue ;;
    -L|--indent)
      set -- "$@" "$a" "$1"; shift; i=$((i + 1)); continue ;;
    -*) set -- "$@" "$a"; continue ;;
  esac
  if [ "$seen" = 0 ]; then seen=1; set -- "$@" "$PRELUDE$a"; else set -- "$@" "$a"; fi
done
exec "$REAL" "$@"
K13JQ
cat > "$JQR_BIN/date" <<'K13DATE'
#!/bin/sh
# generated by tools/regress.d/jq-noregex.sh -- frozen +%s so "Nh ago" cannot flip mid-comparison
[ "${1:-}" = "+%s" ] && { echo "${STARCHORUS_FROZEN_NOW:-0}"; exit 0; }
exec "${STARCHORUS_REAL_DATE:-/bin/date}" "$@"
K13DATE
