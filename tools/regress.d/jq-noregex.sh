jqr_run() { # jqr_run NRX SCREEN JSON OUTFILE
  PATH="$JQR_BIN:$PATH" STARCHORUS_NRX="$1" STARCHORUS_DISPLAY_PLAIN=1 \
  STARCHORUS_REAL_JQ="$JQR_JQ" STARCHORUS_REAL_DATE="$JQR_DATE" STARCHORUS_FROZEN_NOW="$JQR_NOW" \
    sh starchorus-display.sh --once "$2" "$3" > "$4" 2>&1
}

# vacuity guard 1: the wrapper must refuse the regex family and only then
JQR_V1=$(STARCHORUS_NRX=1 STARCHORUS_REAL_JQ="$JQR_JQ" "$JQR_BIN/jq" -n '"abc"|test("b")' 2>&1); JQR_C1=$?
JQR_V2=$(STARCHORUS_NRX=0 STARCHORUS_REAL_JQ="$JQR_JQ" "$JQR_BIN/jq" -n '"abc"|test("b")' 2>&1); JQR_C2=$?
case $JQR_V1 in *"without ONIGURUMA"*) JQR_MSG=ok ;; *) JQR_MSG=missing ;; esac
if [ "$JQR_C1/$JQR_C2/$JQR_V2/$JQR_MSG" = 5/0/true/ok ]; then
  row "no-regex jq wrapper bites (exit 5 / 0, device message)" PASS
else
  row "no-regex jq wrapper $JQR_C1/$JQR_C2/$JQR_V2/$JQR_MSG (want 5/0/true/ok)" FAIL
fi

JQR_CELL=0; JQR_DIFF=0; JQR_SANE=0
for JQR_J in "$F"/*.json; do
  JQR_B=$(basename "$JQR_J" .json)
  for JQR_S in summary top bands devices probes clients air; do
    JQR_CELL=$((JQR_CELL + 1))
    jqr_run 0 "$JQR_S" "$JQR_J" "$JQR_D/$JQR_B.$JQR_S.real"
    jqr_run 1 "$JQR_S" "$JQR_J" "$JQR_D/$JQR_B.$JQR_S.nrx"
    cmp -s "$JQR_D/$JQR_B.$JQR_S.real" "$JQR_D/$JQR_B.$JQR_S.nrx" || {
      JQR_DIFF=$((JQR_DIFF + 1)); echo "    device-jq differs: $JQR_B/$JQR_S"
      diff "$JQR_D/$JQR_B.$JQR_S.real" "$JQR_D/$JQR_B.$JQR_S.nrx" | sed 's/^/      /' | head -n 6; }
  done
  # vacuity guard 2: the simulated summary must carry real band counts ("2.4:<digit>"), which is
  # exactly what a regex filter loses on the device -- empty-none legitimately has none, so it is exempt
  case $JQR_B in empty-none) JQR_SANE=$((JQR_SANE + 1)) ;;
    *) grep -q '2\.4:[0-9]' "$JQR_D/$JQR_B.summary.nrx" && JQR_SANE=$((JQR_SANE + 1)) ;;
  esac
done
JQR_FIX=$(( JQR_CELL / 7 ))
if [ "$JQR_DIFF" = 0 ] && [ "$JQR_SANE" = "$JQR_FIX" ] && [ "$JQR_CELL" -ge 40 ]; then
  row "display script on the device's jq = on the real jq ($JQR_CELL cells, $JQR_SANE/$JQR_FIX with counts)" PASS
else
  row "display script on the device's jq: $JQR_DIFF/$JQR_CELL differ, counts $JQR_SANE/$JQR_FIX" FAIL
fi
# ---- R3 ORACLE: what the normalisation MEANS, pinned by a table.
# R2 above runs the script against itself under two jq builds, so it cannot see the normalisation itself
# move: an edit to _WS or to bandnorm changes both sides equally and R2 still says PASS. In that blind
# spot a narrower whitespace set would pass unnoticed. R3 lifts the
# JQLIB literal straight out of the SHIPPED starchorus-display.sh (never a copy kept in this file) and
# asserts a fixed input -> output table against it, under the real jq AND under the device's.
# The expected column was MEASURED and then reviewed line by line against both reference engines:
#   * jq + Oniguruma, the engine a regex filter would run on: "[[:space:]]" = the 25 Unicode
#     White_Space codepoints, NOT U+FEFF/U+200B/U+180E/U+2060/U+00AD.
#   * the page's own band line in headless Chrome (starchorus.html bandOf, .trim() + /\s*ghz$/i):
#     String.prototype.trim() = the same 25 minus U+0085 plus U+FEFF -- measured at BOTH ends and
#     identical there, so U+FEFF is a MEMBER of the page's trim set, never a near miss.
# They disagree on exactly two codepoints (U+0085 Oniguruma-only, U+FEFF page-only), so _WS is their
# UNION (26). The first EIGHT rows pin that membership exactly and at BOTH ends -- _wsprobe through
# _rtrimws, _lwsprobe through _ltrimws, over the same four partitions: every candidate that must be
# trimmed and every near miss (U+200B/U+180E/U+2060/U+00AD, the C0 controls, plain text) that must
# not. jq -a keeps every value ASCII so this table can never carry an invisible character.
# bandnorm runs _rtrimws at THREE separate points -- inside _trimws before the suffix tests, after
# "ghz" is cut, and after a bare "g" is cut -- and losing any one of them silently un-counts a band.
# The table covers each: "5 " (first), "5 GHz" (second) and "5 g"/"6<NBSP>g" (third, which nothing
# exercised before). Leading whitespace is pinned too: until this fix bandnorm trimmed only the
# right-hand end, so " 5GHz" was counted by the page and dropped by the display script -- the two halves of
# one tool disagreeing. " 5", " 5GHz", "<NBSP>5GHz", "  5  GHz  ", "<FEFF>5GHz" and "<LS>5<LS>" must
# all normalise to "5"; "<ZWSP>5GHz" must NOT, and "<NEL>5GHz" must (the one deliberate divergence
# from the page, taken in the counting direction).
# The row FAILS if the normalisation changes in any direction; that is its whole job.
